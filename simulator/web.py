def serialize_state(session: Session, tcp_status: str = "NOT CONNECTED", udp_status: str = "DISABLED") -> dict[str, Any]:
    """Return a credential-free snapshot for terminal/web consumers."""
    with session.lock:
        stats, measurement = session.statistics, session.last_measurement
        return {
            "source": session.source,
            "replay": session.source == "REPLAY",
            "device": {
                "name": session.device,
                "mode": session.mode,
                "uptime_ms": session.uptime_ms,
                "uptime": format_duration((session.uptime_ms or 0) / 1000),
                "sequence": session.sequence,
                "sequence_gaps": stats.sequence_gaps,
            },
            "connection": {"tcp": tcp_status, "udp": udp_status},
            "session": {
                "samples": stats.samples,
                "normal_samples": stats.normal_samples,
                "test_samples": stats.test_samples,
                "duration_seconds": round(stats.duration_seconds(), 3),
                "duration": format_duration(stats.duration_seconds()),
            },
            "simulated_rf": {
                "label": "SOFTWARE-SIMULATED RF METRICS — not physical ESP32 measurements",
                "rssi_dbm": measurement.rssi_dbm if measurement else None,
                "noise_dbm": measurement.noise_dbm if measurement else None,
                "packet_success_percent": measurement.packet_success_percent if measurement else None,
            },
            "history": list(session.history),
        }


