def create_app(session: Session | None, status_provider: Callable[[], tuple[str, str]] | None = None,
               command_handler: Callable[[str], None] | None = None) -> Flask:
    app = Flask(__name__)

    @app.get("/")
    def index():
        return render_template_string(PAGE)

    @app.get("/api/state")
    def state():
        if session is None:
            return jsonify({"error": "Session state is unavailable"}), 503
        tcp, udp = status_provider() if status_provider else ("NOT CONNECTED", "DISABLED")
        return jsonify(serialize_state(session, tcp, udp))

    @app.post("/api/control")
    def control():
        payload = request.get_json(silent=True) or {}
        command = payload.get("command")
        if not isinstance(command, str) or command.strip().upper() not in VALID_COMMANDS:
            return jsonify({"error": "Command must be STATUS, ON, or OFF"}), 400
        normalized = command.strip().upper()
        if command_handler is None:
            return jsonify({"error": "Device control is unavailable for this source"}), 409
        try:
            command_handler(normalized)
        except (RuntimeError, ValueError) as error:
            return jsonify({"error": str(error)}), 503
        return jsonify({"ok": True, "message": f"Sent safe command: {normalized}"})

    return app


class WebDashboard:
    """Deterministically stoppable localhost WSGI server."""
    def __init__(self, app: Flask, bind: str = DEFAULT_WEB_BIND, port: int = DEFAULT_WEB_PORT):
        self.bind, self.port = bind, port
        self._server = make_server(bind, port, app, threaded=True)
        self.port = self._server.server_port
        self._thread = Thread(target=self._server.serve_forever, name="embedded-rf-web", daemon=False)

    @property
    def url(self) -> str:
        host = "127.0.0.1" if self.bind in {"0.0.0.0", "::"} else self.bind
        return f"http://{host}:{self.port}"

    def start(self) -> None:
        self._thread.start()

    def close(self) -> None:
        self._server.shutdown()
        self._thread.join(timeout=5)
        self._server.server_close()
